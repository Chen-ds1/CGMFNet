import argparse
import hashlib
import json
import math
import random
from datetime import datetime
from pathlib import Path
import numpy as np
import torch
from torch.utils.data import DataLoader
from prsgnet.data import RowDataset, collate
from prsgnet.model import PRSGNet
from prsgnet.loss import criterion
from prepare_labelme import PROJECT, convert
from prsgnet.runtime import load_config, resolve, device_name


def parser(argv=None):
    config, config_path = load_config(argv)
    p = argparse.ArgumentParser(description='Train PRSGNet on LabelMe row annotations.')
    p.add_argument('--config', default=str(config_path))
    p.add_argument('--labelme-dir', type=Path, default=resolve(config['data']['labelme_dir']))
    p.add_argument('--data-out', type=Path, default=resolve(config['data']['manifest_dir']))
    p.add_argument('--grouping', choices=['capture', 'day'], default=config['data']['grouping'])
    p.add_argument('--labels', nargs='+', default=config['data']['labels'])
    p.add_argument('--rebuild-data', action='store_true', help='Regenerate manifests after annotation changes; otherwise reuse existing splits')
    p.add_argument('--train', type=Path, help='Optional JSONL; omit to use inputs automatically')
    p.add_argument('--val', type=Path)
    p.add_argument('--out', type=Path, help='Default: a NEW timestamped directory under runs/')
    p.add_argument('--epochs', type=int, default=config['train']['epochs'])
    p.add_argument('--batch-size', type=int, default=config['train']['batch_size'])
    p.add_argument('--lr', type=float, default=config['train']['lr'])
    p.add_argument('--weight-decay', type=float, default=config['train']['weight_decay'])
    p.add_argument('--workers', type=int, default=config['train']['workers'])
    p.add_argument('--device', default=config['train']['device'])
    pretraining = p.add_mutually_exclusive_group()
    pretraining.add_argument('--pretrained', dest='pretrained', action='store_true')
    pretraining.add_argument('--no-pretrained', dest='pretrained', action='store_false')
    p.set_defaults(pretrained=config['train']['pretrained'])
    p.add_argument('--resume', type=Path)
    p.add_argument('--max-steps', type=int, default=0, help='Debug train batches per epoch; 0=all')
    p.add_argument('--seed', type=int, default=config['data']['seed'])
    return p


def fingerprint(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest() if path else None


def main(argv=None):
    a = parser(argv).parse_args(argv)
    for key in ('labelme_dir','data_out','train','val','out','resume'):
        if getattr(a,key) is not None:
            setattr(a,key,resolve(getattr(a,key)))
    a.device = device_name(a.device)
    if a.epochs < 1 or a.batch_size < 1 or a.max_steps < 0:
        raise ValueError('epochs/batch-size must be positive; max-steps must be nonnegative')
    if a.resume and a.pretrained:
        raise ValueError('--resume and --pretrained must not be combined')
    random.seed(a.seed); np.random.seed(a.seed); torch.manual_seed(a.seed)
    torch.set_num_threads(4)
    if a.device.startswith('cuda') and not torch.cuda.is_available():
        raise RuntimeError('CUDA unavailable. Use --device cpu or install a matching CUDA PyTorch build.')
    saved = torch.load(a.resume, map_location='cpu', weights_only=False) if a.resume else None
    if saved:
        if saved.get('dataset_source') != 'manual_labelme':
            raise ValueError('Do not resume old pseudo-label weights; start a fresh manual-label run.')
        for key in ('epochs', 'batch_size', 'seed', 'lr', 'weight_decay'):
            if getattr(a,key) != saved['args'][key]:
                raise ValueError(f'Resume requires the original {key}={saved["args"][key]}')
        if a.train is None:
            a.train = Path(saved['args']['train'])
            a.val = Path(saved['args']['val']) if saved['args'].get('val') else None
    if a.train is None:
        manifests = {split:a.data_out/(split+'.jsonl') for split in ('train','val','test')}
        if a.rebuild_data or not all(path.is_file() for path in manifests.values()):
            manifests = convert(a.labelme_dir, a.data_out, a.seed, a.labels, a.grouping)
        a.train = manifests['train']
        if a.val is None:
            a.val = manifests['val']
    a.train = a.train.resolve()
    if a.val:
        a.val = a.val.resolve()
    hashes = {'train': fingerprint(a.train), 'val': fingerprint(a.val)}
    if saved and saved['manifest_hashes'] != hashes:
        raise ValueError('Manifests changed since checkpoint; refusing mismatched resume.')
    train_data = RowDataset(a.train, augment=True)
    val_data = RowDataset(a.val) if a.val else None
    if any(r.get('label_source') != 'manual_labelme' for r in train_data.records):
        raise ValueError('This entry point requires manual_labelme manifests generated by prepare_labelme.py.')
    if val_data:
        overlap = {r['image'] for r in train_data.records} & {r['image'] for r in val_data.records}
        if overlap:
            raise ValueError(f'Train/val overlap: {len(overlap)} images')
    out = a.out.resolve() if a.out else (a.resume.resolve().parent if a.resume else PROJECT/'runs'/datetime.now().strftime('labelme_%Y%m%d_%H%M%S_%f'))
    if (out/'last.pt').exists() and not saved:
        raise FileExistsError(f'{out} already contains weights; choose a new --out or --resume')
    out.mkdir(parents=True, exist_ok=True)
    args = {k: str(v) if isinstance(v,Path) else v for k,v in vars(a).items()}
    args['out'] = str(out)
    config_name = 'resume_config.json' if saved else 'config.json'
    (out/config_name).write_text(json.dumps(args,indent=2,ensure_ascii=False),encoding='utf-8')
    (out/'dataset_provenance.json').write_text(json.dumps({'dataset_source':'manual_labelme','manifest_hashes':hashes},indent=2),encoding='utf-8')
    loader = DataLoader(train_data,batch_size=a.batch_size,shuffle=True,num_workers=a.workers,collate_fn=collate)
    val = DataLoader(val_data,batch_size=a.batch_size,num_workers=a.workers,collate_fn=collate) if val_data else None
    net = PRSGNet(pretrained=a.pretrained).to(a.device)
    optimizer = torch.optim.AdamW(net.parameters(),lr=a.lr,weight_decay=a.weight_decay)
    schedule = torch.optim.lr_scheduler.LambdaLR(optimizer,lambda e:((1+math.cos(math.pi*min(e,a.epochs)/a.epochs))/2)**.9)
    start, best = 0, float('inf')
    if saved:
        net.load_state_dict(saved['model']); optimizer.load_state_dict(saved['optimizer']); schedule.load_state_dict(saved['scheduler'])
        start, best = saved['epoch']+1, saved['best']
        random.setstate(saved['rng_python']); np.random.set_state(saved['rng_numpy']); torch.set_rng_state(saved['rng_torch'].cpu())
        if torch.cuda.is_available() and saved.get('rng_cuda') is not None:
            torch.cuda.set_rng_state_all([s.cpu() for s in saved['rng_cuda']])
        if start >= a.epochs:
            print(f'Checkpoint already completed {start} epochs; no training needed.'); return
    print(f'Device: {a.device}; train={len(train_data)}, val={len(val_data) if val_data else 0}; output={out}',flush=True)
    for epoch in range(start,a.epochs):
        net.train(); train_sum, train_count = 0., 0
        for step,(images,targets) in enumerate(loader):
            images = images.to(a.device)
            targets = [{k:v.to(a.device) for k,v in t.items()} for t in targets]
            optimizer.zero_grad(set_to_none=True)
            loss,parts = criterion(net(images),targets)
            if not torch.isfinite(loss):
                raise RuntimeError(f'Nonfinite loss: {parts}')
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(),10,error_if_nonfinite=True)
            optimizer.step()
            train_sum += float(loss.detach())*len(images); train_count += len(images)
            if a.max_steps and step+1 >= a.max_steps:
                break
        validation = None
        if val:
            net.eval(); val_sum, val_count = 0., 0
            with torch.no_grad():
                for images,targets in val:
                    targets = [{k:v.to(a.device) for k,v in t.items()} for t in targets]
                    value,_ = criterion(net(images.to(a.device),auxiliary=True),targets)
                    if not torch.isfinite(value):
                        raise RuntimeError('Nonfinite validation loss')
                    val_sum += float(value)*len(images); val_count += len(images)
            validation = val_sum/val_count
        schedule.step()
        metric = validation if validation is not None else train_sum/train_count
        improved = metric < best; best = min(best,metric)
        checkpoint = {'model':net.state_dict(),'optimizer':optimizer.state_dict(),'scheduler':schedule.state_dict(),
                      'epoch':epoch,'best':best,'args':args,'dataset_source':'manual_labelme','manifest_hashes':hashes,
                      'rng_python':random.getstate(),'rng_numpy':np.random.get_state(),'rng_torch':torch.get_rng_state(),
                      'rng_cuda':torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None}
        torch.save(checkpoint,out/'last.pt')
        if improved:
            torch.save(checkpoint,out/'best.pt')
        record = {'epoch':epoch+1,'train_loss':train_sum/train_count,'val_loss':validation,'parts_last_batch':parts}
        with (out/'history.jsonl').open('a',encoding='utf-8') as file:
            file.write(json.dumps(record)+'\n')
        print(json.dumps(record),flush=True)
    print(f'Completed. Best weights: {out / "best.pt"}',flush=True)


if __name__ == '__main__':
    main()
